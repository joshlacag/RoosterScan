## The 17 Keypoints Explained

### Head Region (Points 1-3)

**1. Beak Tip**
- **Location:** The very front point of the upper beak
- **Purpose:** Helps assess head position and alertness
- **Health Indicator:** Abnormal beak angle may indicate neck or neurological issues
- **Detection Difficulty:** Easy (90-95% confidence typically)

**2. Eye**
- **Location:** Mid-head, center of the eye
- **Purpose:** Critical for detecting head tilt or asymmetry
- **Health Indicator:** Eye position reveals balance and neurological health
- **Detection Difficulty:** Easy (85-95% confidence)

**3. Comb Top**
- **Location:** Highest point of the comb
- **Purpose:** Indicates overall head carriage and posture
- **Health Indicator:** Drooping or tilted comb suggests weakness or illness
- **Detection Difficulty:** Moderate (75-90% confidence, varies by breed)

### Neck & Body (Points 4-7)

**4. Neck Base**
- **Location:** Where the neck meets the body, at the shoulder line
- **Purpose:** Important for posture assessment and spine alignment
- **Health Indicator:** Abnormal angle suggests neck injury or respiratory distress
- **Detection Difficulty:** Moderate (80-90% confidence)

**5. Chest/Breast**
