## Common Keypoint Detection Issues

### Low Confidence Scores

**Usually caused by:**
- Poor lighting (dark, shadowy images)
- Blurry images (camera shake or bird movement)
- Obstructed view (feeders, other birds, bedding)
- Unusual poses (sitting, lying, turning)
- Low image resolution
- Extreme camera angles

**Solutions:**
- Improve lighting conditions
- Use steady camera or tripod
- Clear the area of obstructions
- Wait for natural standing pose
- Use higher resolution camera
- Shoot at bird''s level

### Missing Keypoints

**May occur when:**
- Body part not visible in photo
- Feathers obscure the area (especially legs)
- Extreme angles used
- Image quality too low
- Bird in unusual position
- Background too busy

**Solutions:**
- Ensure full body visible
- Use profile view
- Improve image quality
- Wait for better pose
- Use plain background
- Take multiple photos

### Inconsistent Detection

**Common causes:**
- Varying photo quality
- Different angles or lighting
- Bird in different poses
- Seasonal changes (molting)
- Different camera or settings

**Solutions:**
- Maintain consistent photo conditions
- Use same angle and distance
- Document any changes
- Account for seasonal variations
- Standardize your photo process

## Breed-Specific Considerations

Different breeds have different normal keypoint positions:

**Game Breeds (Asil, Shamo, etc.):**
- More upright posture
- Higher tail carriage
- Muscular breast
- Wider stance

**Large Breeds (Brahma, Cochin, etc.):**
- Lower, heavier body
- Broader stance
- More horizontal back
- Feathered legs (may obscure keypoints)

**Bantam Breeds:**
- More compact proportions
- Higher activity level
- Smaller keypoint spacing
- May need closer camera distance

**Know your breed''s normal anatomy to accurately interpret keypoint data!**

