## Why These Points Matter

### Symmetry Analysis

The AI compares left and right keypoints to detect asymmetry, which often indicates:

**Wing Symmetry**
- Both wings should be at equal height
- Tips should align when relaxed
- Shoulders should be level
- **Asymmetry indicates:** Wing injuries, muscle weakness, or nerve damage

**Leg Symmetry**
- Both legs should bear equal weight
- Hip and knee angles should match
- Feet should be evenly positioned
- **Asymmetry indicates:** Limping, bumblefoot, leg injuries, or arthritis

**Body Balance**
- Spine should be straight
- Weight centered over both legs
- Head and tail aligned
- **Imbalance indicates:** Spinal issues, neurological problems, or compensating for injury

### Posture Assessment

Keypoint relationships reveal critical health information:

**Head-to-Tail Alignment**
- Straight line indicates healthy spine
- Curvature suggests spinal problems
- Tilt indicates balance issues
- **Normal:** Smooth curve from head through tail
- **Abnormal:** S-curve, sharp angles, or severe tilt

**Wing Height and Position**
- Both wings at same height
- Held close to body
- Feathers neatly folded
- **Normal:** Symmetrical, relaxed carriage
- **Abnormal:** One wing lower, dragging, or held away from body

**Leg Angles and Stance**
- Legs perpendicular to ground
- Weight evenly distributed
- Knees and hips at normal angles
- **Normal:** Upright, balanced stance
- **Abnormal:** Crouching, favoring one leg, or wide stance

**Weight Distribution**
- Balanced over both feet
- Center of gravity stable
- No leaning or tilting
- **Normal:** Centered, confident stance
- **Abnormal:** Leaning, unsteady, or compensating

### Movement Patterns

When analyzing multiple images over time, keypoint tracking shows:

**Gait Consistency**
- Regular stride length
- Even weight transfer
- Smooth movement
- **Indicates:** Overall leg and joint health

**Range of Motion**
- Full wing extension
- Normal leg flexion
- Head mobility
- **Indicates:** Joint health and flexibility

**Compensation Behaviors**
- Favoring one side
- Altered posture
- Unusual movements
- **Indicates:** Pain, injury, or developing problems

**Progressive Changes**
- Gradual shifts in posture
- Developing asymmetry
- Declining mobility
- **Indicates:** Chronic conditions or aging issues

